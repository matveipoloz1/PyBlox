def load_lang():
    global LANG
    try:
        with open(PROFILE_FILE, 'r', encoding='utf-8') as f:
            p = json.load(f)
        lang = p.get('language', 'ru')
        if lang in TEXTS:
            LANG = lang
    except Exception:
        pass


def set_lang(lang):
    global LANG
    if lang not in TEXTS:
        return
    LANG = lang
    try:
        prof = {}
        if os.path.exists(PROFILE_FILE):
            with open(PROFILE_FILE, 'r', encoding='utf-8') as f:
                prof = json.load(f)
        prof['language'] = lang
        with open(PROFILE_FILE, 'w', encoding='utf-8') as f:
            json.dump(prof, f, ensure_ascii=False, indent=2)
    except Exception:
        pass


def t(key, **kw):
    s = TEXTS.get(LANG, {}).get(key)
    if not s:
        s = TEXTS['ru'].get(key) or key
    if kw:
        try:
            return s.format(**kw)
        except Exception:
            return s
    return s


